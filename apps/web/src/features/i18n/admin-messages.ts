export type AdminMessage = keyof typeof de;

export function isAdminLocale(value: unknown): value is AdminLocale {
  return value === "de" || value === "en";
}

export function translateAdmin(locale: AdminLocale, message: string) {
  return locale === "de" ? (de[message as AdminMessage] ?? message) : message;
}
